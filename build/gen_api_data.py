"""
Generates api/_data.js from the source-of-truth files (the persona doc and the
menu data), so the Vercel serverless function never has to read files at
request time — everything it needs is baked into one plain JS module that
ships with the function.

Run this whenever Sullivan_人设文档.md or menu_data.min.json changes:
    python3 build/gen_api_data.py
"""
import json
import pathlib

BASE = pathlib.Path(__file__).resolve().parent
PROJECT_DIR = BASE.parent
PERSONA_PATH = PROJECT_DIR / "Sullivan_人设文档.md"
MENU_PATH = BASE / "menu_data.min.json"
OUT_PATH = PROJECT_DIR / "api" / "_data.js"

persona_doc = PERSONA_PATH.read_text(encoding="utf-8")

menu = json.loads(MENU_PATH.read_text(encoding="utf-8"))
lines = []
for d in menu["dishes"]:
    taste = ",".join(d.get("taste", []))
    mood = ",".join(d.get("mood", []))
    lines.append(f'{d["id"]}: {d["cn"]}/{d["en"]} [{d.get("category","")}] taste={taste} mood={mood}')
menu_catalog = "\n".join(lines)

OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
OUT_PATH.write_text(
    "// AUTO-GENERATED by build/gen_api_data.py — do not edit by hand.\n"
    "// Source: Sullivan_人设文档.md + build/menu_data.min.json\n"
    "module.exports.PERSONA_DOC = " + json.dumps(persona_doc, ensure_ascii=False) + ";\n"
    "module.exports.MENU_CATALOG = " + json.dumps(menu_catalog, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print("wrote", OUT_PATH)
